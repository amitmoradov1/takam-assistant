"""חילוץ הפניות צולבות בין הוראות תכ"ם.

הוראות תכ"ם מפנות זו לזו באופן שיטתי. ההפניות האלה הן ידע דומיין יקר:
כשעובד שואל על מכרז, ההוראות שההוראה הרלוונטית מפנה אליהן (ואלה שמפנות
אליה) הן בדיוק "מה עוד כדאי לו לקרוא".

שני סגנונות הפניה (השני הוא התחביר הקנוני במסמכים האמיתיים שנאספו מהאתר):
1. ישיר:   "בהתאם להוראת תכ"ם 7.12.3"
2. עם שם:  'בהתאם להוראת תכ"ם, "התקשרות בהליך מקוצר", מס' 7.7.1'

דיוק לפני כיסוי: מחלצים רק מספרים שמופיעים בהקשר "הוראה/הוראת/הוראות"
(ובסגנון 2 — אחרי "מס'") ולא כל מספר היררכי בטקסט, כי מספור הסעיפים
הפנימי של המסמך (3.1, 2.3.1) נראה זהה והיה מייצר הפניות-סרק.
"""

from __future__ import annotations

import re

_NUMBER = r"(\d{1,2}(?:\.\d{1,2}){1,4})"
_QUOTES = "[\"”„״'׳`]"

# סגנון 1: ב/ל/כ/ש/מ/ו + הוראה/הוראת/הוראות, אופציונלית "תכ"ם", ואז המספר
_DIRECT_RE = re.compile(
    rf"(?:[בלכשמו]?הורא(?:ה|ת|ות))\s+(?:תכ{_QUOTES}{{0,2}}ם\s+)?{_NUMBER}"
)

# סגנון 2: הוראת תכ"ם, "שם ההוראה", מס' 7.7.1 (וריאציות גרשיים; לעיתים
# נקודה תועה לפני המספר: "מס' .7.9.1")
_TITLED_RE = re.compile(
    rf"הורא(?:ה|ת|ות)\s+תכ{_QUOTES}{{0,2}}ם[^\n]{{0,100}}?"
    rf"מס{_QUOTES}{{0,2}}\s*\.?\s*{_NUMBER}"
)


def extract_references(text: str, own_number: str = "") -> list[str]:
    """מספרי ההוראות שהטקסט מפנה אליהן, ייחודיים ולפי סדר הופעה,
    ללא הפניה-עצמית."""
    matches = [(m.start(), m.group(1)) for pattern in (_TITLED_RE, _DIRECT_RE)
               for m in pattern.finditer(text)]
    matches.sort()

    seen: set[str] = set()
    references: list[str] = []
    for _, number in matches:
        if number == own_number or number in seen:
            continue
        seen.add(number)
        references.append(number)
    return references
